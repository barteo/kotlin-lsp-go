// TestMavenModel reads a two-module reactor's effective POM and the
// dependency plugin's class paths.
func TestMavenModel(t *testing.T) {
	root := t.TempDir()
	repo := filepath.Join(root, "repo")
	for _, d := range []string{"lib/src/main/kotlin", "app/src/main/kotlin", "app/src/main/java", "app/src/test/kotlin", "app/target/generated-sources/gen"} {
		os.MkdirAll(filepath.Join(root, d), 0o755)
	}
	jar := func(rel string) string {
		p := filepath.Join(repo, rel)
		os.MkdirAll(filepath.Dir(p), 0o755)
		os.WriteFile(p, nil, 0o644)
		return p
	}
	stdlib := jar("org/jetbrains/kotlin/kotlin-stdlib/2.2.0/kotlin-stdlib-2.2.0.jar")
	junit := jar("junit/junit/4.13.2/junit-4.13.2.jar")
	libJar := jar("com/example/lib/1.0/lib-1.0.jar")
	r := func(s string) string { return strings.ReplaceAll(s, "ROOT", root) }
	pom := r(`<?xml version="1.0" encoding="UTF-8"?>
<!-- ====================================================================== -->
<!-- Generated by Maven Help Plugin                                         -->
<projects>
  <project>
    <groupId>com.example</groupId><artifactId>parent</artifactId><version>1.0</version><packaging>pom</packaging>
  </project>
  <project>
    <parent><groupId>com.example</groupId><artifactId>parent</artifactId><version>1.0</version></parent>
    <artifactId>lib</artifactId><version>1.0</version>
    <properties><kotlin.compiler.jvmTarget>17</kotlin.compiler.jvmTarget></properties>
    <build>
      <sourceDirectory>ROOT/lib/src/main/java</sourceDirectory>
      <testSourceDirectory>ROOT/lib/src/test/java</testSourceDirectory>
      <outputDirectory>ROOT/lib/target/classes</outputDirectory>
      <testOutputDirectory>ROOT/lib/target/test-classes</testOutputDirectory>
      <directory>ROOT/lib/target</directory>
      <plugins><plugin><groupId>org.jetbrains.kotlin</groupId><artifactId>kotlin-maven-plugin</artifactId>
        <configuration><args><arg>-Xexplicit-api=strict</arg><arg>-opt-in=kotlin.RequiresOptIn</arg></args>
          <compilerPlugins><plugin>kotlinx-serialization</plugin></compilerPlugins></configuration>
      </plugin></plugins>
    </build>
  </project>
  <project>
    <groupId>com.example</groupId><artifactId>app</artifactId><version>1.0</version>
    <dependencies>
      <dependency><groupId>com.example</groupId><artifactId>lib</artifactId><version>1.0</version><scope>compile</scope></dependency>
      <dependency><groupId>org.jetbrains.kotlin</groupId><artifactId>kotlin-stdlib</artifactId><version>2.2.0</version><scope>compile</scope></dependency>
      <dependency><groupId>junit</groupId><artifactId>junit</artifactId><version>4.13.2</version><scope>test</scope></dependency>
    </dependencies>
    <build>
      <sourceDirectory>ROOT/app/src/main/java</sourceDirectory>
      <testSourceDirectory>ROOT/app/src/test/java</testSourceDirectory>
      <outputDirectory>ROOT/app/target/classes</outputDirectory>
      <testOutputDirectory>ROOT/app/target/test-classes</testOutputDirectory>
      <directory>ROOT/app/target</directory>
      <plugins>
        <plugin><artifactId>kotlin-maven-plugin</artifactId>
          <executions><execution><id>compile</id><goals><goal>compile</goal></goals>
            <configuration><jvmTarget>21</jvmTarget><sourceDirs><sourceDir>ROOT/app/src/main/kotlin</sourceDir><sourceDir>src/main/java</sourceDir></sourceDirs></configuration>
          </execution></executions>
        </plugin>
        <plugin><artifactId>build-helper-maven-plugin</artifactId>
          <executions><execution><goals><goal>add-source</goal></goals>
            <configuration><sources><source>target/generated-sources/gen</source></sources></configuration></execution></executions>
        </plugin>
      </plugins>
    </build>
  </project>
</projects>
`)
	projects, err := parseEffectivePOM([]byte(pom))
	if err != nil {
		t.Fatal(err)
	}
	if len(projects) != 3 {
		t.Fatalf("%d projects", len(projects))
	}
	log := r(`[INFO] Scanning for projects...
[INFO] ------------------------< com.example:lib >-------------------------
[INFO] --- dependency:3.7.0:build-classpath (default-cli) @ lib ---
[INFO] Dependencies classpath:

[INFO] ------------------------< com.example:app >-------------------------
[INFO] --- maven-dependency-plugin:2.8:build-classpath (default-cli) @ app ---
[INFO] Dependencies classpath:
` + libJar + ":" + stdlib + `
[INFO] BUILD SUCCESS
`)
	cps := parseBuildClasspath(log)
	if got := cps["app"]; !slices.Equal(got, []string{libJar, stdlib}) || cps["lib"] != nil {
		t.Fatalf("class paths %q", cps)
	}
	// The test scope didn't resolve: the direct dependencies stand in.
	w := fromMaven(root, projects, map[string]map[string][]string{"compile": cps, "test": {}}, repo)
	var got []string
	for _, m := range w.Modules {
		rel := func(ps []string) string {
			var out []string
			for _, p := range ps {
				p, _ = filepath.Rel(root, p)
				out = append(out, filepath.ToSlash(p))
			}
			return strings.Join(out, ",")
		}
		got = append(got, m.ID+" name="+m.ModuleName+" roots="+rel(m.Roots)+" cp="+rel(m.ClassPath)+" friends="+rel(m.FriendPaths)+
			" deps="+strings.Join(m.DependsOn, ",")+" jvm="+m.JVMTarget+" api="+m.ExplicitAPI+" plugins="+strings.Join(m.Plugins, ",")+
			" optins="+strings.Join(m.OptIns, ",")+" dir="+filepath.Base(m.Dir))
	}
	want := []string{
		"lib:main name=lib roots=lib/src/main/kotlin cp= friends= deps= jvm=17 api=strict plugins=serialization optins=kotlin.RequiresOptIn dir=lib",
		"app:main name=app roots=app/src/main/kotlin,app/src/main/java,app/target/generated-sources/gen cp=repo/org/jetbrains/kotlin/kotlin-stdlib/2.2.0/kotlin-stdlib-2.2.0.jar friends= deps=lib:main jvm=21 api= plugins= optins= dir=app",
		"app:test name=app_test roots=app/src/test/kotlin cp=app/target/classes,repo/org/jetbrains/kotlin/kotlin-stdlib/2.2.0/kotlin-stdlib-2.2.0.jar,repo/junit/junit/4.13.2/junit-4.13.2.jar friends=app/target/classes deps=app:main,lib:main jvm= api= plugins= optins= dir=app",
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Errorf("modules:\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	_ = junit

	// One module: <project> at the top.
	one, err := parseEffectivePOM([]byte(`<?xml version="1.0"?><project><artifactId>solo</artifactId></project>`))
	if err != nil || len(one) != 1 || one[0].ArtifactID != "solo" {
		t.Errorf("one project: %+v, %v", one, err)
	}
	os.WriteFile(filepath.Join(root, "pom.xml"), []byte("<project/>"), 0o644)
	if got := Detect(root); got != "maven" {
		t.Errorf("Detect = %s", got)
	}
}

func TestNonJVMSourceSet(t *testing.T) {
	for path, want := range map[string]string{
		"/p/shared/src/commonMain/kotlin/a/A.kt":  "commonMain",
		"/p/shared/src/jsMain/kotlin/A.kt":        "jsMain",
		"/p/shared/src/iosArm64Test/kotlin/A.kt":  "iosArm64Test",
		"/p/shared/src/wasmJsMain/kotlin/A.kt":    "wasmJsMain",
		"/p/shared/src/jvmMain/kotlin/A.kt":       "",
		"/p/shared/src/desktopMain/kotlin/A.kt":   "",
		"/p/app/src/main/kotlin/A.kt":             "",
		"/p/app/src/javascript/kotlin/A.kt":       "",
		"/p/shared/src/commonMain/resources/a.kt": "",
	} {
		if got := NonJVMSourceSet(path); got != want {
			t.Errorf("NonJVMSourceSet(%s) = %q, want %q", path, got, want)
		}
	}
}

// TestImportMaven imports a two-module Maven build: a library and an
// application with a test. It runs Maven, so it needs KCLS_MAVEN_TEST=1
// and mvn on PATH or KCLS_MAVEN naming it, and Maven's help and
// dependency plugins and kotlin-stdlib in the local repository or
// reachable online.
func TestImportMaven(t *testing.T) {
	if os.Getenv("KCLS_MAVEN_TEST") != "1" {
		t.Skip("KCLS_MAVEN_TEST=1 runs Maven")
	}
	mvn := os.Getenv("KCLS_MAVEN")
	if mvn == "" {
		var err error
		if mvn, err = exec.LookPath("mvn"); err != nil {
			t.Skip("no mvn on PATH and no KCLS_MAVEN")
		}
	}
	root, _ := filepath.EvalSymlinks(t.TempDir())
	const stdlib = `<dependency><groupId>org.jetbrains.kotlin</groupId><artifactId>kotlin-stdlib</artifactId><version>2.2.0</version></dependency>`
	pom := func(artifact, deps, build string) string {
		return `<project xmlns="http://maven.apache.org/POM/4.0.0"><modelVersion>4.0.0</modelVersion>
<parent><groupId>com.example</groupId><artifactId>parent</artifactId><version>1.0</version></parent>
<artifactId>` + artifact + `</artifactId><dependencies>` + stdlib + deps + `</dependencies>` + build + `</project>`
	}
	write(t, root, map[string]string{
		"pom.xml": `<project xmlns="http://maven.apache.org/POM/4.0.0"><modelVersion>4.0.0</modelVersion>
<groupId>com.example</groupId><artifactId>parent</artifactId><version>1.0</version><packaging>pom</packaging>
<properties><kotlin.compiler.jvmTarget>17</kotlin.compiler.jvmTarget></properties>
<modules><module>lib</module><module>app</module></modules></project>`,
		"lib/pom.xml": pom("lib", "", `<build><plugins><plugin><groupId>org.jetbrains.kotlin</groupId><artifactId>kotlin-maven-plugin</artifactId><version>2.2.0</version>
<configuration><args><arg>-Xexplicit-api=strict</arg></args></configuration></plugin></plugins></build>`),
		"app/pom.xml": pom("app", `<dependency><groupId>com.example</groupId><artifactId>lib</artifactId><version>1.0</version></dependency>
<dependency><groupId>junit</groupId><artifactId>junit</artifactId><version>4.13.2</version><scope>test</scope></dependency>`, ""),
		"lib/src/main/kotlin/L.kt":  "package lib\npublic fun lib(): Int = 1\n",
		"app/src/main/kotlin/A.kt":  "fun main() = println(lib.lib())\n",
		"app/src/test/kotlin/AT.kt": "fun t() = main()\n",
	})
	script := "#!/bin/sh\nexec " + mvn + " \"$@\"\n"
	if err := os.WriteFile(filepath.Join(root, "mvnw"), []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	defer cancel()
	w, err := ImportMaven(ctx, root, GradleOptions{CacheDir: t.TempDir(), Logf: t.Logf})
	if err != nil {
		t.Fatal(err)
	}
	app, lib, test := w.ByID("app:main"), w.ByID("lib:main"), w.ByID("app:test")
	if app == nil || lib == nil || test == nil {
		t.Fatalf("modules: %+v", w.Modules)
	}
	if !slices.Contains(app.DependsOn, "lib:main") || !slices.Contains(test.DependsOn, "app:main") {
		t.Errorf("app depends on %v, its test on %v", app.DependsOn, test.DependsOn)
	}
	if lib.ExplicitAPI != "strict" || lib.JVMTarget != "17" {
		t.Errorf("lib: explicit API %q, JVM target %q", lib.ExplicitAPI, lib.JVMTarget)
	}
	has := func(m *Module, name string) bool {
		return slices.ContainsFunc(m.ClassPath, func(e string) bool { return strings.HasPrefix(filepath.Base(e), name) })
	}
	if !has(app, "kotlin-stdlib") || has(app, "junit") || !has(test, "junit") || has(app, "lib-") {
		t.Errorf("class paths: app %v, test %v", app.ClassPath, test.ClassPath)
	}
}
